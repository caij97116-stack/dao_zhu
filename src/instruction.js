// src/instruction.js — 岛主历险记：内置「抗弱模型」格式指令（由扩展自动注入聊天系统提示，无需用户复制）
//
// 设计目标（对应需求四“AI 不读正则 → 美化显示不出来”）：
//   弱模型常出现两类问题 —— ① 格式漂移（大小写/空格/漏闭合）；② 输出到一半就断掉、
//   漏字段、留半个标签。下面指令刻意做到：重复性强、歧义小、并显式要求
//   “必须完整输出 [card]…[/card] 闭合并一次给全”，尽量把格式拉回本插件可解析的范围。
//
// 注意：本插件【默认自动注入】该指令到聊天系统提示（见 index.js 的 registerBuiltinFormatInstruction），
// 不改动你的预设/角色卡文件，你无需手动复制粘贴。
// 若你想自己按角色微调、或担心与其它预设冲突，可在设置面板关掉「自动内置注入格式指令」，
// 关闭后退回手动模式（面板仍展示该指令，可一键复制做备用）。

export const FORMAT_INSTRUCTION = `【结构化信息格式指令（必须严格遵守）】
当你需要展示角色面板、状态、物品栏、属性等“结构化信息”时，只能在正文中使用下面这一种格式，不要使用 Markdown 表格、不要使用代码块、不要自创其他格式：

[card]
title=面板标题
theme=blue
字段名: 字段值
字段名: 字段值
[/card]

硬性规则（逐条遵守，不要省略）：
1. 每段结构化信息必须以 [card] 开头、以 [/card] 结尾；标签必须成对且完整闭合，绝对不能漏写 [/card]。
2. 标签名固定为 card（小写英文），不要写 [Card]、[卡片]、<card>、{{card}} 等任何变体。
3. 字段用「键: 值」或「键=值」其中一种写法，冒号/等号前后不要加多余空格。
4. 一次可以输出多个 [card]…[/card] 块，但每一个都必须独立、完整地闭合。
5. 普通对话文字写在 [card] 块之外，不要塞进卡片里。
6. 内容再长，也必须把整段 [card]…[/card] 一次性完整输出，绝不在中间断句、绝不省略字段、绝不留半个标签。`;

